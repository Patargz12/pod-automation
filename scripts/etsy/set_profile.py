"""
set_profile.py — Move listings off one shipping profile onto another
=====================================================================
`fix_profile.py` solves ONE hardcoded case (the Monster Digital orphan profile
308327773212 -> 308167021214). This is the same operation with the profiles as
arguments, written for the free-shipping removal.

WHY THIS EXISTS

Profile 295057919524 ("Printful: Free Shipping (#PF-FRGFREE)") charges P0.00 to
all 11 of its destinations, and 20 live listings sit on it. Free shipping does
not make postage free — Printful still bills it — so on those listings the
`ship` term stops cancelling out of the margin formula and becomes pure cost:

    net = 0.89 * price          - P37.37 - cost - ship     <- free shipping
    net = 0.89 * (price + ship) - P37.37 - cost - ship     <- postage charged

That P0.00 is why 4433996964 (a Gildan 18000 crewneck priced at tee money,
P1,928.50) nets NEGATIVE P943 on an Australian order and negative P108 even in
the US.

WHAT IT CHANGES

`shipping_profile_id` is a single integer on the listing. Swapping it changes
which saved rate card the listing quotes. It does NOT edit a rate on any
profile, re-publish anything, call Printify or Printful, or touch images, text,
price or state. Every write is read back from Etsy before it is counted.

THE PRICE IS A SEPARATE DECISION — READ THIS

The 17 tees on the free profile are priced P1,934-2,015 against a tee ladder
base of P1,604. That P330-411 gap IS the postage, carried in the item price
(WhatToDo.md: "the free-shipping tees carry postage in the item price"). Move
them to a profile that also charges postage and the buyer pays it TWICE.

  · the 17 tees   -> move AND drop to the tee ladder (P1,604 / 1,789 / 1,974)
  · the 3 fleeces -> move AND raise to the sweatshirt ladder (they are underwater)

This script only moves profiles. It prints the price gap so the pairing is not
forgotten, but repricing is a stop-and-ask item and is not automated here.

THE PRINTFUL CAVEAT

These 20 listings are not in either Printify ledger — they are legacy Printful
listings, and #PF- profiles are generated by Printful's own Etsy integration.
A Printful re-sync can reassert the old profile the same way Printify does
(see set_shipping_profile's note). Re-run --verify after any sync.

USAGE
  python -m scripts.etsy.set_profile                          # dry run, auto-routed by garment
  python -m scripts.etsy.set_profile --apply                  # commit
  python -m scripts.etsy.set_profile --to 312495877008        # force one target for everything
  python -m scripts.etsy.set_profile --from 295057919524      # source (default: the free profile)
  python -m scripts.etsy.set_profile --verify
  python -m scripts.etsy.set_profile --restore caching/profile_backup_YYYYMMDD_HHMMSS.json

Backups are written in fix_profile.py's format ({listing_id: old_profile_id}),
so either script's --restore reads either script's backup.
Runs append to caching/profile_log.txt.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except (AttributeError, ValueError):
    pass

from services.etsy_service import EtsyClient, EtsyError
from services.printify_service import SWEATSHIRT_PROFILE, TEE_PROFILE
from scripts.etsy.audit import garment_of, active_listings

CACHE_DIR = Path("caching")
LOG_FILE = CACHE_DIR / "profile_log.txt"

# Charges P0.00 to every destination it names.
FREE_PROFILE = 295057919524

# Where each garment belongs when --to is not given. Both charge real postage.
AUTO_TARGET = {
    "sweatshirt": 312495877008,   # Standard: Printful, Hoodie, Sweatshirt (56 listings, AU P1,360)
    "tee":        295077566750,   # Printful: Tshirts (#PF-FRG1)           (AU P422)
}

LADDER_BASE = {
    "sweatshirt": min(SWEATSHIRT_PROFILE.price_by_size.values()),
    "tee":        min(TEE_PROFILE.price_by_size.values()),
}


def _log(line: str = "") -> None:
    print(line)
    CACHE_DIR.mkdir(exist_ok=True)
    with LOG_FILE.open("a", encoding="utf-8") as fh:
        fh.write(line + "\n")


def _banner(title: str) -> None:
    _log()
    _log("=" * 74)
    _log(f"  {title}")
    _log("=" * 74)


def _profiles(client: EtsyClient, shop_id: int) -> dict[int, dict]:
    return {p["shipping_profile_id"]: p
            for p in client.get_shipping_profiles(shop_id)}


def _price(listing: dict) -> float:
    p = listing.get("price") or {}
    return p.get("amount", 0) / (p.get("divisor") or 1)


def _rate(profile: dict | None, iso: str) -> float | None:
    """What this profile charges to `iso`, falling back to its rest-of-world row."""
    if not profile:
        return None
    fallback = None
    for d in profile.get("shipping_profile_destinations") or []:
        cost = (d.get("primary_cost") or {})
        amt = cost.get("amount", 0) / (cost.get("divisor") or 1)
        if d.get("destination_country_iso") == iso:
            return amt
        if not d.get("destination_country_iso"):
            fallback = amt
    return fallback


def _plan(client: EtsyClient, shop_id: int, source: int,
          forced: int | None) -> list[tuple[dict, str, int]]:
    """Everything on `source`, paired with the profile it should move to."""
    rows = [L for L in active_listings(client, shop_id)
            if L.get("shipping_profile_id") == source]
    out = []
    for L in rows:
        garment = garment_of(L.get("title", ""))
        target = forced or AUTO_TARGET.get(garment)
        out.append((L, garment, target))
    return out


def _report(plan, profiles, source) -> None:
    src = profiles.get(source)
    _log(f"  source  {source}  {(src or {}).get('title', '- gone -')[:56]}")
    _log(f"          AU P{_rate(src, 'AU') or 0:,.2f}   US P{_rate(src, 'US') or 0:,.2f}"
         f"   · {len(plan)} listing(s)")
    _log()
    _log(f"  {'listing':<12}{'garment':<11}{'price':>9}{'ladder':>9}{'gap':>8}   -> target")
    for L, garment, target in sorted(plan, key=lambda x: (x[1], -_price(x[0]))):
        price = _price(L)
        base = LADDER_BASE.get(garment)
        gap = f"{price - base:+,.0f}" if base else "?"
        _log(f"  {L['listing_id']:<12}{garment:<11}{price:>9,.0f}"
             f"{(base or 0):>9,.0f}{gap:>8}   -> {target or '?? no route'}")

    _log()
    for pid in sorted({t for _, _, t in plan if t}):
        p = profiles.get(pid)
        n = sum(1 for _, _, t in plan if t == pid)
        _log(f"  target  {pid}  {(p or {}).get('title', '- gone -')[:56]}")
        _log(f"          AU P{_rate(p, 'AU') or 0:,.2f}   US P{_rate(p, 'US') or 0:,.2f}"
             f"   · {n} listing(s) inbound")

    over = [(L, garment) for L, garment, _ in plan
            if LADDER_BASE.get(garment) and _price(L) > LADDER_BASE[garment] + 1]
    if over:
        _log()
        _log(f"  !!  {len(over)} listing(s) are priced ABOVE their ladder base — that")
        _log("      margin is the postage, carried in the item price. Charging")
        _log("      shipping on top bills the buyer twice. Reprice with these moves.")


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Move listings from one shipping profile to another.")
    ap.add_argument("--from", dest="source", type=int, default=FREE_PROFILE,
                    help=f"source profile id (default {FREE_PROFILE}, the free one)")
    ap.add_argument("--to", dest="target", type=int,
                    help="force one target for every listing (default: route by garment)")
    ap.add_argument("--only", metavar="ID,ID",
                    help="restrict to these listing ids (the rest stay put)")
    ap.add_argument("--apply", action="store_true", help="commit (default: dry run)")
    ap.add_argument("--verify", action="store_true")
    ap.add_argument("--restore", metavar="BACKUP.json")
    args = ap.parse_args()

    client = EtsyClient()
    shop_id = client.get_shop_id()

    if args.restore:
        _banner("Shipping profile · RESTORE")
        saved = json.loads(Path(args.restore).read_text(encoding="utf-8"))
        for lid, pid in saved.items():
            client.set_shipping_profile(shop_id, int(lid), int(pid))
            _log(f"  <- {lid}  back to profile {pid}")
        _log(f"\n  restored: {len(saved)}")
        return 0

    profiles = _profiles(client, shop_id)
    plan = _plan(client, shop_id, args.source, args.target)

    if args.only:
        keep = {int(x) for x in args.only.replace(" ", "").split(",") if x}
        plan = [row for row in plan if row[0]["listing_id"] in keep]
        missing = keep - {row[0]["listing_id"] for row in plan}
        if missing:
            _log(f"  note: {sorted(missing)} not on profile {args.source} — skipped")

    if args.verify:
        _banner("Shipping profile · VERIFY")
        _report(plan, profiles, args.source)
        _log()
        if plan:
            _log(f"  x {len(plan)} listing(s) still on {args.source}")
            return 1
        _log(f"  ok - nothing is left on {args.source}")
        return 0

    _banner(f"Shipping profile · {'APPLY' if args.apply else 'DRY RUN'}")
    _report(plan, profiles, args.source)
    _log()

    if not plan:
        _log("  ok - nothing to move.")
        return 0

    unroutable = [L["listing_id"] for L, _, t in plan if not t]
    if unroutable:
        _log(f"  x no target for {unroutable} — garment not identifiable from the")
        _log("    title. Pass --to explicitly, or fix the title first.")
        return 1

    if not args.apply:
        _log(f"  Would move {len(plan)} listing(s). Nothing was written.")
        _log("  Re-run with --apply to commit. Only shipping_profile_id changes:")
        _log("  no re-publish, no Printful/Printify call, no change to price or state.")
        return 0

    CACHE_DIR.mkdir(exist_ok=True)
    backup_path = CACHE_DIR / f"profile_backup_{time.strftime('%Y%m%d_%H%M%S')}.json"
    backup_path.write_text(
        json.dumps({str(L["listing_id"]): L["shipping_profile_id"]
                    for L, _, _ in plan}, indent=2), encoding="utf-8")
    _log(f"  Backup written: {backup_path}")
    _log(f"  Undo with:  python -m scripts.etsy.set_profile --restore {backup_path}")
    _log()

    moved, failed = 0, 0
    for L, _, target in plan:
        lid = L["listing_id"]
        try:
            client.set_shipping_profile(shop_id, lid, target)
        except EtsyError as exc:
            _log(f"  x {lid}  {exc}")
            failed += 1
            continue
        live = client.get_listing(lid).get("shipping_profile_id")   # trust Etsy, not the write
        if live == target:
            _log(f"  ok {lid}  now on {target}, confirmed live")
            moved += 1
        else:
            _log(f"  x {lid}  wrote {target} but Etsy reports {live}")
            failed += 1

    _log()
    _log("=" * 74)
    _log(f"  moved  : {moved}")
    _log(f"  failed : {failed}")
    _log("=" * 74)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
